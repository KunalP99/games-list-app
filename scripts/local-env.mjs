/**
 * Writes .env.dev.local pointing at the local Supabase stack.
 *
 * Usage (after `npm run supabase:start`):
 *   npm run env:local
 *
 * Takes the API URL and keys from `supabase status` and carries over every
 * other setting (RAWG/IGDB/YouTube keys, METADATA_PROVIDER) from
 * .env.prod.local, so the local environment differs only where it must.
 *
 * The local anon/service_role keys are fixed demo credentials baked into the
 * Supabase CLI — identical on every machine, and useless outside your laptop.
 */

import fs from 'fs'
import path from 'path'
import { createRequire } from 'module'
import { spawnSync } from 'child_process'

const ROOT = process.cwd()
const require = createRequire(import.meta.url)

function parseEnvFile(file) {
  const out = new Map()
  if (!fs.existsSync(file)) return out
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eq = trimmed.indexOf('=')
    if (eq === -1) continue
    out.set(trimmed.slice(0, eq).trim(), trimmed.slice(eq + 1).trim())
  }
  return out
}

let cliPath
try {
  cliPath = require.resolve('supabase/dist/supabase.js')
} catch {
  console.error('Supabase CLI not installed. Run: npm install --save-dev supabase')
  process.exit(1)
}

const status = spawnSync(process.execPath, [cliPath, 'status', '-o', 'json'], { encoding: 'utf8' })
if (status.status !== 0) {
  console.error('Could not read local Supabase status. Is the stack running?')
  console.error('Start it with: npm run supabase:start')
  if (status.stderr) console.error(status.stderr.trim())
  process.exit(1)
}

let info
try {
  // `status -o json` can be preceded by log lines; take the JSON object only.
  const json = status.stdout.slice(status.stdout.indexOf('{'))
  info = JSON.parse(json)
} catch {
  console.error('Could not parse `supabase status -o json` output.')
  process.exit(1)
}

const apiUrl = info.API_URL
const anonKey = info.ANON_KEY
const serviceKey = info.SERVICE_ROLE_KEY
const dbUrl = info.DB_URL

if (!apiUrl || !anonKey || !serviceKey) {
  console.error('Local Supabase status did not include the expected URL/keys.')
  process.exit(1)
}

// Everything that isn't project-specific comes from the production env file.
const shared = parseEnvFile(path.join(ROOT, '.env.prod.local'))
const PROJECT_SPECIFIC = new Set([
  'NEXT_PUBLIC_SUPABASE_URL',
  'NEXT_PUBLIC_SUPABASE_ANON_KEY',
  'SUPABASE_SERVICE_ROLE_KEY',
  'SUPABASE_DB_URL',
  'NEXT_PUBLIC_APP_ENV',
])

const lines = [
  '# ── LOCAL Supabase stack (Docker) ──────────────────────────────────────',
  '# Generated by scripts/local-env.mjs — re-run `npm run env:local` after',
  '# `supabase start` if the ports ever change.',
  '#',
  '# Activate with:  npm run env:dev        Check with:  npm run env',
  '# Studio UI:      http://127.0.0.1:54323',
  '',
  '# Shows the "TEST DATABASE" pill in the UI. Never set this in production.',
  'NEXT_PUBLIC_APP_ENV=development',
  '',
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
  dbUrl ? `SUPABASE_DB_URL=${dbUrl}` : '',
  '',
  '# Carried over from .env.prod.local (same third-party services):',
]

for (const [key, value] of shared) {
  if (PROJECT_SPECIFIC.has(key)) continue
  lines.push(`${key}=${value}`)
}

fs.writeFileSync(path.join(ROOT, '.env.dev.local'), lines.filter(l => l !== '').join('\n') + '\n')
console.log('Wrote .env.dev.local pointing at the local stack.')
console.log(`  API:    ${apiUrl}`)
console.log( '  Studio: http://127.0.0.1:54323')
console.log('\nNext:  npm run env:dev && npm run db:reset && npm run seed:dev')
